export const TEXT = { en: EN, es: ES };

export function t(lang, key, register = 'plain', vars = {}) {
  const table = { ...EN, ...(TEXT[lang] || {}) };
  const raw = table[`${key}_${register}`] ?? table[key] ?? key;
  return raw.replace(/\{(\w+)\}/g, (_, k) => (k in vars ? String(vars[k]) : `{${k}}`));
}

export function locale(lang) {
  return lang === 'es' ? 'es-ES' : 'en-US';
}
